#!/usr/bin/env python3
"""gen_fsrfg.py: FSR 3.1 frame interpolation and optical flow (vk/third_party/fsr3) compiled to SPIR-V, with each pass's
bindings read from the module, as vk/fsrfg_passes_spv.inc (nvn_vulkan_fsrfg.inc). Run by gen_shaders.sh; needs
glslangValidator and spirv-dis. The SDK's own host library takes its shaders from blobs made by a Windows compiler, so
the passes are run from nvn_vulkan_fsrfg.inc. FP16 is not an option: FFX_HALF adds no half types to the GLSL path."""
import re, struct, subprocess, sys, tempfile
from pathlib import Path
vk = Path(__file__).resolve().parents[1]/'vk'
out = vk/'fsrfg_passes_spv.inc'
G = vk/'third_party/fsr3/gpu'
D = ['FFX_GPU=1', 'FFX_GLSL=1', 'FFX_HALF=0', 'FFX_FRAMEINTERPOLATION_OPTION_LOW_RES_MOTION_VECTORS=1',
     'FFX_FRAMEINTERPOLATION_OPTION_JITTER_MOTION_VECTORS=0', 'FFX_FRAMEINTERPOLATION_OPTION_INVERTED_DEPTH=0',
     'FFX_OPTICALFLOW_OPTION_HDR_COLOR_INPUT=0']
# our name: source
PASSES = {
    'fi_dilate': 'frameinterpolation/ffx_frameinterpolation_reconstruct_and_dilate_pass', 'fi_setup': 'frameinterpolation/ffx_frameinterpolation_setup_pass',
    'fi_prev_depth': 'frameinterpolation/ffx_frameinterpolation_reconstruct_previous_depth_pass', 'fi_game_mv': 'frameinterpolation/ffx_frameinterpolation_game_motion_vector_field_pass',
    'fi_game_pyr': 'frameinterpolation/ffx_frameinterpolation_compute_game_vector_field_inpainting_pyramid_pass', 'fi_of_field': 'frameinterpolation/ffx_frameinterpolation_optical_flow_vector_field_pass',
    'fi_disocc': 'frameinterpolation/ffx_frameinterpolation_disocclusion_mask_pass', 'fi_interp': 'frameinterpolation/ffx_frameinterpolation_pass',
    'fi_pyr': 'frameinterpolation/ffx_frameinterpolation_compute_inpainting_pyramid_pass', 'fi_inpaint': 'frameinterpolation/ffx_frameinterpolation_inpainting_pass',
    'of_luma': 'opticalflow/ffx_opticalflow_prepare_luma_pass', 'of_pyr': 'opticalflow/ffx_opticalflow_compute_luminance_pyramid_pass',
    'of_hist': 'opticalflow/ffx_opticalflow_generate_scd_histogram_pass', 'of_div': 'opticalflow/ffx_opticalflow_compute_scd_divergence_pass',
    'of_search': 'opticalflow/ffx_opticalflow_compute_optical_flow_advanced_pass_v5', 'of_filter': 'opticalflow/ffx_opticalflow_filter_optical_flow_pass_v5',
    'of_scale': 'opticalflow/ffx_opticalflow_scale_optical_flow_advanced_pass_v5'}
KIND = dict(sampled=0, storage=1, ubo=2, ssbo=3, sampler=4)
def reflect(spv):
    d = subprocess.run(['spirv-dis', '--raw-id', spv], capture_output=True, text=True, check=True).stdout
    names = dict(re.findall(r'OpName %(\d+) "([^"]*)"', d)); bind = dict(re.findall(r'OpDecorate %(\d+) Binding (\d+)', d))
    types = {m[1]: (m[2], m[3].split()) for m in re.finditer(r'^\s*%(\d+) = (OpType\w+)(.*)$', d, re.M)}
    res = []
    for v, t, sc in re.findall(r'%(\d+) = OpVariable %(\d+) (\w+)', d):
        if v not in bind: continue
        ty = types[types[t][1][1].lstrip('%')]
        if ty[0] == 'OpTypeImage': k, fmt = ('storage', ty[1][6]) if ty[1][5] == '2' else ('sampled', '')
        elif ty[0] == 'OpTypeSampler': k, fmt = 'sampler', ''
        elif ty[0] == 'OpTypeStruct': k, fmt = ('ssbo' if sc == 'StorageBuffer' or names.get(v, '').startswith(('rw_', 'r_')) else 'ubo'), ''
        else: raise SystemExit(f'{spv}: {names.get(v)}: {ty}')
        res.append((int(bind[v]), names[v], k, fmt))
    return sorted(res)
lines = ['/* Generated by tools/gen_fsr_spike.py from AMD FidelityFX SDK v1.1.4 (MIT): do not edit. */']
table = []
with tempfile.TemporaryDirectory() as tmp:
    for name, src in PASSES.items():
        o = f'{tmp}/{name}.spv'
        r = subprocess.run(['glslangValidator', '-V', '--target-env', 'vulkan1.2', '-S', 'comp', *[f'-D{x}' for x in D],
                            f'-I{G}', f'-I{G}/frameinterpolation', f'-I{G}/opticalflow', f'-I{G}/spd', str(vk/'third_party/fsr3/shaders'/f'{src}.glsl'), '-o', o], capture_output=True, text=True)
        if r.returncode: raise SystemExit(r.stdout)
        b = reflect(o)
        code = Path(o).read_bytes(); w = struct.unpack(f'<{len(code)//4}I', code)
        lines.append(f'static const uint32_t fsr_code_{name}[] = {{' + ','.join(map(str, w)) + '};')
        lines.append(f'static const fsr_binding fsr_bind_{name}[] = {{' + ','.join(f'{{{i},{KIND[k]},"{n}"}}' for i, n, k, _ in b) + '};')
        table.append(f'    {{"{name}", fsr_code_{name}, sizeof fsr_code_{name}, fsr_bind_{name}, {len(b)}}},')
        print(name, len(code), [(n, f) for _, n, k, f in b if k == 'storage' and f != 'Unknown'])
lines += ['static const fsr_pass_source fsr_passes[] = {', *table, '};', 'enum { ' + ', '.join(f'FSR_{n.upper()}' for n in PASSES) + ', FSR_PASSES };']
out.write_text('\n'.join(lines) + '\n'); print(out, out.stat().st_size)
